import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
 for (const width of [390,1440]) {
  const page=await browser.newPage({viewport:{width,height:1000},reducedMotion:'reduce'})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(`${process.env.URL??'http://127.0.0.1:5178/'}#catalogo`,{waitUntil:'domcontentloaded'})
  await page.getByRole('navigation',{name:'Categorías del catálogo'}).getByRole('button',{name:'Aparadores',exact:true}).click()
  assert.equal(await page.locator('.catalog-card').count(),6)
  await page.getByRole('button',{name:'Vista rápida de Aparador Arian'}).click()
  const dialog=page.getByRole('dialog')
  await dialog.waitFor({state:'visible'})
  assert.match(await dialog.innerText(),/Precio por confirmar/)
  assert.equal(await dialog.getByRole('button',{name:/Agregar .* al carrito/}).count(),0)
  await dialog.getByRole('button',{name:'Azul mediterráneo y dorado',exact:true}).click()
  const image=dialog.locator('.catalog-preview__image')
  await image.evaluate(el=>el.decode())
  assert.match(await image.getAttribute('src'),/azul/)
  const first=await image.getAttribute('src')
  await dialog.getByRole('button',{name:/Ver foto 2/}).click()
  assert.notEqual(await image.getAttribute('src'),first)
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('button',{name:'Vista rápida de Aparador Arian'}).evaluate(el=>el===document.activeElement),true)
  await page.getByLabel('Buscar en el catálogo').fill('200100001001')
  assert.equal(await page.locator('.catalog-card').count(),1)
  await page.getByRole('button',{name:'Vista rápida de Aparador Escanor'}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Agregar Aparador Escanor al carrito'}).click()
  assert.match(await page.locator('.cart-notice').innerText(),/Escanor/)
  await page.locator('.catalog-page__cart').click()
  await page.getByRole('dialog',{name:'Tu carrito'}).waitFor({state:'visible'})
  assert.match(await page.locator('.cart-summary').innerText(),/959/)
  await page.getByRole('button',{name:'Cerrar carrito'}).click()
  await page.getByRole('button',{name:'Limpiar filtros'}).click()
  await page.getByRole('button',{name:'Todas las categorías',exact:true}).click()
  assert.equal(await page.locator('.catalog-menu__links button').count(),31)
  await page.locator('.catalog-menu__links').getByRole('button',{name:'Zapateras',exact:true}).click()
  assert.equal(await page.locator('.catalog-card').count(),0)
  await page.getByRole('button',{name:'Limpiar filtros'}).click()
  assert.equal(await page.locator('.catalog-card').count(),12)
  await page.screenshot({path:`.screenshots/catalog-new-${width}.png`,fullPage:false})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  assert.deepEqual(errors,[])
  await page.goto(`${process.env.URL??'http://127.0.0.1:5178/'}#catalogo?categoria=aparadores`,{waitUntil:'domcontentloaded'})
  await page.waitForFunction(()=>document.querySelectorAll('.catalog-card').length===6)
  await page.goto(`${process.env.URL??'http://127.0.0.1:5178/'}#inicio`,{waitUntil:'domcontentloaded'})
  assert.equal(await page.locator('#tienda .product').count(),2)
  assert.equal(await page.locator('#tienda .categories').count(),0)
  console.log(`PASS ${width}: acceso directo, 31 categorías, búsqueda SKU, galería/acabados, precios pendientes, carrito y portada mínima`)
  await page.close()
 }
} finally {await browser.close()}
