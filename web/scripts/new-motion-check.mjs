import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const browser=await chromium.launch({channel:'chrome',headless:true})
const url=process.env.URL??'http://localhost:5173/'
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'})
 const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text())})
 await page.goto(url,{waitUntil:'networkidle'})
 assert.ok(await page.locator('.hero .split-word').count()>3)
 await page.waitForTimeout(1700)
 const before=await page.locator('.hero__media').evaluate(el=>getComputedStyle(el).transform)
 await page.evaluate(()=>scrollTo(0,450));await page.waitForTimeout(800)
 assert.notEqual(await page.locator('.hero__media').evaluate(el=>getComputedStyle(el).transform),before)
 const image=page.getByRole('button',{name:'Ver detalles de Aparador Escanor',exact:true})
 assert.equal(await image.locator('img').evaluate(el=>getComputedStyle(el).viewTransitionName),'product-escanor')
 await image.click();await page.getByRole('dialog',{name:'Aparador Escanor',exact:true}).waitFor()
 assert.equal(await page.locator('.product-details__image').evaluate(el=>getComputedStyle(el).viewTransitionName),'product-escanor')
 await page.keyboard.press('Escape');await page.waitForTimeout(600)
 await page.waitForFunction(() => !document.documentElement.hasAttribute('data-view-transition'))
 const card=page.locator('.product').first()
 await card.scrollIntoViewIfNeeded();const box=await card.boundingBox()
 await page.mouse.move(box.x+box.width*.8,box.y+box.height*.3);await page.waitForTimeout(350)
 assert.ok(await card.evaluate(el=>Math.abs(new DOMMatrix(getComputedStyle(el).transform).m13)>.001),'La tarjeta se inclina con el cursor')
 await page.mouse.move(5,5)
 await page.getByRole('link',{name:'Ver catálogo completo',exact:true}).click()
 await page.getByRole('heading',{name:'Catálogo completo',exact:true}).waitFor()
 assert.equal(await page.locator('.product').count(),7)
 await page.getByRole('link',{name:'Volver al inicio',exact:true}).click()
 await page.locator('#showroom').scrollIntoViewIfNeeded();await page.locator('canvas').waitFor()
 await page.getByRole('tab',{name:'Dormitorio',exact:true}).click();await page.waitForTimeout(1600)
 assert.equal(await page.getByRole('tab',{name:'Dormitorio',exact:true}).getAttribute('aria-selected'),'true')
 assert.ok(await page.getByText('Un espacio para descansar.',{exact:true}).isVisible())
 const canvas=page.locator('canvas');const view=await canvas.boundingBox()
 await canvas.click({position:{x:view.width*.675,y:view.height*.426}})
 assert.equal(await page.getByRole('button',{name:'Ropero',exact:true}).getAttribute('aria-pressed'),'true')
 await page.getByRole('tab',{name:'Sala',exact:true}).click();await page.waitForTimeout(1400)
 await page.getByRole('button',{name:'Desplazar',exact:true}).click()
 assert.equal(await page.getByRole('button',{name:'Desplazar',exact:true}).getAttribute('aria-pressed'),'true')
 await page.getByRole('button',{name:'Restablecer vista',exact:true}).click()
 assert.equal(await page.getByRole('button',{name:'Desplazar',exact:true}).getAttribute('aria-pressed'),'false')
 await page.getByRole('tab',{name:'Sala',exact:true}).focus();await page.keyboard.press('ArrowRight')
 assert.equal(await page.getByRole('tab',{name:'Comedor',exact:true}).getAttribute('aria-selected'),'true')
 await page.locator('#servicios').scrollIntoViewIfNeeded()
 assert.equal(await page.locator('.services-story').evaluate(el=>getComputedStyle(el).position),'sticky')
 await page.locator('.bento__cell').last().scrollIntoViewIfNeeded();await page.waitForTimeout(800)
 assert.equal(await page.locator('.services-story__title').innerText(),'Instalación y montaje')
 await page.emulateMedia({reducedMotion:'reduce'})
 assert.equal(await page.locator('.services-story').evaluate(el=>getComputedStyle(el).position),'static')
 assert.deepEqual(errors,[])
 console.log('PASS máscara, texto dividido, scroll del Hero, elemento compartido, páginas, tres ambientes, selección, controles, sticky y movimiento reducido')
 await page.close()
 const fallback=await browser.newPage({viewport:{width:390,height:1000},reducedMotion:'no-preference'})
 await fallback.addInitScript(() => Object.defineProperty(document, 'startViewTransition', {value:undefined}))
 await fallback.goto(url,{waitUntil:'networkidle'})
 await fallback.getByRole('button',{name:'Ver detalles de Aparador Escanor',exact:true}).click()
 await fallback.getByRole('dialog',{name:'Aparador Escanor',exact:true}).waitFor()
 await fallback.keyboard.press('Escape')
 await fallback.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Ver detalles de Aparador Escanor')
 await fallback.getByRole('link',{name:'Ver catálogo completo',exact:true}).click()
 await fallback.getByRole('heading',{name:'Catálogo completo',exact:true}).waitFor()
 await fallback.close()
 console.log('PASS navegación y ficha sin soporte de View Transitions')
} finally {await browser.close()}
