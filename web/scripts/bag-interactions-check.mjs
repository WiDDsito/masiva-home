import assert from 'node:assert/strict'
import {chromium} from 'playwright-core'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
 for(const width of [390,1440]) {
  const page=await browser.newPage({viewport:{width,height:1000},reducedMotion:'reduce'})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(`${process.env.URL??'http://127.0.0.1:5182/'}#inicio`,{waitUntil:'domcontentloaded'})
  const add=page.getByRole('button',{name:'Agregar Aparador Escanor al carrito',exact:true})
  await add.click();await add.click()
  const bag=page.getByRole('button',{name:'Carrito, 2 productos',exact:true})
  await bag.waitFor({state:'visible'})
  assert.equal(await page.locator('.cart-count').innerText(),'2')
  const notice=page.locator('.cart-notice.is-visible')
  await notice.waitFor({state:'visible'})
  assert.match(await notice.innerText(),/Agregado a tu bolsa/)
  assert.ok((await notice.boundingBox()).width>300)
  await notice.getByRole('button',{name:'Ver bolsa (2)',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Tu carrito',exact:true})
  await dialog.waitFor({state:'visible'})
  assert.match(page.url(),/#inicio$/)
  assert.match(await page.locator('.cart-summary').innerText(),/1,918/)
  await page.getByRole('button',{name:'Aumentar cantidad de Aparador Escanor'}).click()
  assert.equal(await page.locator('.cart-count').innerText(),'3')
  await page.getByRole('button',{name:'Cerrar carrito'}).click()
  await page.getByRole('button',{name:'Carrito, 3 productos',exact:true}).click()
  await dialog.waitFor({state:'visible'})
  assert.match(page.url(),/#inicio$/)
  await page.keyboard.press('Escape')
  await page.reload({waitUntil:'domcontentloaded'})
  await page.getByRole('button',{name:'Carrito, 3 productos',exact:true}).waitFor()
  await page.getByRole('link',{name:'Ver catálogo completo',exact:true}).click()
  await page.getByRole('heading',{name:'Catálogo de muebles',exact:true}).waitFor()
  await page.getByRole('button',{name:'Carrito, 3 productos',exact:true}).click()
  await dialog.waitFor({state:'visible'})
  assert.match(page.url(),/#catalogo$/)
  await page.getByRole('button',{name:'Eliminar Aparador Escanor',exact:true}).click()
  assert.equal(await page.locator('.cart-count').innerText(),'0')
  assert.match(await dialog.innerText(),/Tu próximo mueble te espera/)
  assert.deepEqual(errors,[])
  console.log(`PASS ${width}: bolsa actualizada, aviso visible, acceso sin redirección, cantidades y persistencia`)
  await page.close()
 }
}finally{await browser.close()}
