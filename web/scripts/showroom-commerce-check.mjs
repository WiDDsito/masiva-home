import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
 for(const width of [390,1440]) {
  const page=await browser.newPage({viewport:{width,height:1000},reducedMotion:'reduce'})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(process.env.URL??'http://localhost:5173/',{waitUntil:'networkidle'})
  await page.locator('#showroom').scrollIntoViewIfNeeded()
  await page.getByRole('button',{name:'Centro de mesa',exact:true}).click()
  const panel=page.locator('.showroom__caption.has-selection')
  assert.ok((await panel.innerText()).includes('S/ 659.00'))
  assert.ok(parseFloat(await panel.locator('.showroom__price').evaluate(el=>getComputedStyle(el).fontSize))>=16)
  await panel.getByRole('button',{name:'Agregar Mesa de centro Fabela al carrito',exact:true}).click({timeout:4000})
  assert.equal(await page.getByRole('button',{name:'Centro de mesa',exact:true}).getAttribute('aria-pressed'),'true')
  assert.equal(await page.evaluate(()=>location.hash),'')
  await page.getByRole('button',{name:'Carrito, 1 productos'}).click()
  assert.ok((await page.getByRole('dialog',{name:'Tu carrito'}).innerText()).includes('Mesa de centro Fabela'))
  assert.ok((await page.locator('.cart-summary').innerText()).includes('S/ 659.00'))
  await page.keyboard.press('Escape')
  await panel.getByRole('button',{name:'Agregar Mesa de centro Fabela al carrito',exact:true}).click()
  await page.getByRole('button',{name:'Carrito, 2 productos'}).waitFor()
  await page.getByRole('button',{name:'Mesa de TV',exact:true}).click()
  assert.ok((await panel.innerText()).includes('S/ 1,379.00'))
  await panel.getByRole('button',{name:'Agregar Mesa de TV Kevin al carrito',exact:true}).click()
  await page.getByRole('button',{name:'Carrito, 3 productos'}).waitFor()
  await page.getByRole('link',{name:'Explorar el catálogo',exact:true}).click()
  await page.getByRole('heading',{name:'Catálogo completo',exact:true}).waitFor()
  const filter=page.getByRole('combobox',{name:'Filtrar por categoría'})
  const names=await filter.locator('option').allTextContents()
  for(const name of ['Aparadores','Archivadores','Armarios','Bancos de bar','Cómodas y cajoneras','Counters y recibidores','Escritorios','Estantes','Juegos de comedor','Libreros','Mesas consola','Mesas auxiliares','Mesas de centro','Mesas de comedor','Mesas de TV','Muebles de baño','Muebles bar','Percheros','Repisas','Reposteros','Roperos','Sillas','Soportes de cama','Tocadores','Veladores','Zapateras','Baúles','Cabeceras','Casas para mascotas','Maceteros','Carpetas / Pupitres']) assert.ok(names.includes(name),name)
  assert.equal(await page.locator('.catalog-toolbar select').count(),2)
  await filter.selectOption('mesas-de-centro')
  assert.equal(await page.locator('.product').count(),2)
  await filter.selectOption('aparadores')
  assert.equal(await page.locator('.product').count(),1)
  await filter.selectOption('roperos')
  assert.ok((await page.locator('.product').innerText()).includes('Runa'))
  await filter.selectOption('maceteros')
  assert.ok(await page.getByRole('heading',{name:'No encontramos esa pieza.'}).isVisible())
  await page.getByRole('button',{name:'Limpiar filtros'}).click()
  assert.equal(await page.locator('.product').count(),7)
  await page.getByRole('button',{name:'Carrito, 3 productos'}).click()
  assert.ok((await page.locator('.cart-summary').innerText()).includes('S/ 2,697.00'))
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  assert.deepEqual(errors,[])
  console.log(`PASS ${width}px: precio en showroom, compra directa, selección conservada, carrito compartido y categorías completas`)
  await page.close()
 }
} finally {await browser.close()}
