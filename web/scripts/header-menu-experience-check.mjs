import assert from 'node:assert/strict'
import {chromium} from 'playwright-core'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
 for(const width of [390,768,1024,1440]) {
  const page=await browser.newPage({viewport:{width,height:1000},reducedMotion:'reduce'})
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`)})
  await page.goto(process.env.URL??'http://127.0.0.1:5180/',{waitUntil:'domcontentloaded'})
  const video=page.locator('video.hero__video')
  await video.waitFor()
  assert.ok(await video.getAttribute('src'))
  assert.equal(await video.getAttribute('poster'), null)
  assert.ok(await video.evaluate(el => el.paused))
  assert.equal(await video.getAttribute('preload'),'auto')
  assert.ok(await video.evaluate(el=>el.muted&&el.defaultMuted&&el.volume===0&&el.loop&&el.playsInline))
  if(width>900) {
   const trigger=page.getByRole('button',{name:'Tienda',exact:true})
   await trigger.hover();await trigger.click()
   assert.equal(await trigger.getAttribute('aria-expanded'),'true','Clic tras hover mantiene el panel abierto')
   await page.mouse.move(width-30,900);await page.waitForTimeout(300)
   assert.equal(await trigger.getAttribute('aria-expanded'),'true','El panel fijado por clic no se cierra al salir')
   await page.mouse.click(width-30,900)
   assert.equal(await trigger.getAttribute('aria-expanded'),'false')
   await trigger.focus();await page.keyboard.press('ArrowDown')
   await page.waitForFunction(()=>document.activeElement?.classList.contains('mega__all'))
   await page.keyboard.press('Tab')
   assert.match(await page.evaluate(()=>document.activeElement?.textContent),/Aparadores/)
   await page.keyboard.press('Tab')
   await page.locator('#mega-tienda .mega__feature img').evaluate(img=>img.decode())
   assert.equal(await page.locator('#mega-tienda .mega__feature').getAttribute('aria-label'),'Ver mesas de centro')
   await page.screenshot({path:`.screenshots/header-menu-${width}.png`})
   await page.keyboard.press('Escape')
   assert.equal(await trigger.getAttribute('aria-expanded'),'false')
   assert.ok(await trigger.evaluate(el=>el===document.activeElement))
   await trigger.click()
   await page.locator('#mega-tienda .mega__feature').click()
   await page.waitForURL(/categoria=mesas-de-centro/)
   await page.locator('.catalog-card').first().waitFor()
   assert.equal(await page.locator('.catalog-card').count(),2)
   await page.evaluate(()=>scrollTo(0,450));await page.waitForTimeout(400)
   await trigger.hover()
   const box=await trigger.boundingBox()
   await page.mouse.move(box.x+box.width/2,box.y+box.height+4,{steps:10});await page.waitForTimeout(300)
   assert.equal(await trigger.getAttribute('aria-expanded'),'true','También funciona con la cabecera compactada')
   await page.mouse.move(width-30,900);await page.waitForTimeout(300)
   assert.equal(await trigger.getAttribute('aria-expanded'),'false','El hover se cierra al salir realmente del panel')
  }else{
   await page.getByRole('button',{name:'Abrir menú',exact:true}).click()
   await page.locator('.mobile-shop summary').click()
   await page.screenshot({path:`.screenshots/header-menu-${width}.png`})
   await page.locator('#mega-tienda-movil').getByRole('button',{name:/Aparadores/}).first().click()
   await page.waitForURL(/categoria=aparadores/)
   await page.locator('.catalog-card').first().waitFor()
   assert.equal(await page.locator('.catalog-card').count(),8)
   assert.equal(await page.locator('.mobile-nav').count(),0)
  }
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  assert.deepEqual(errors,[])
  console.log(`PASS ${width}: video moderno silenciado, menú estable, navegación por categoría y sin errores`)
  await page.close()
 }
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'})
 await page.goto(process.env.URL??'http://127.0.0.1:5180/',{waitUntil:'domcontentloaded'})
 await page.waitForFunction(()=>{const v=document.querySelector('video');return v?.readyState>=2&&!v.paused})
 await page.getByRole('button',{name:'Pausar video de portada'}).click()
 assert.ok(await page.locator('video').evaluate(el=>el.paused))
 await page.getByRole('button',{name:'Reproducir video de portada'}).click()
 await page.waitForFunction(()=>!document.querySelector('video')?.paused)
 await page.locator('video').evaluate(el=>{el.muted=false;el.volume=1})
 await page.waitForFunction(()=>{const v=document.querySelector('video');return v?.muted&&v.volume===0})
 console.log('PASS reproducción, pausa y silencio forzado del nuevo video')
}finally{await browser.close()}
