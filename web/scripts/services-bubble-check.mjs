import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'})
 await page.goto(process.env.URL??'http://localhost:5173/',{waitUntil:'networkidle'})
 const cell=page.locator('.bento__cell').first()
 await cell.scrollIntoViewIfNeeded();await page.waitForTimeout(800)
 const rect=await cell.boundingBox()
 await page.mouse.move(rect.x-5,rect.y+rect.height/2)
 await page.mouse.move(rect.x+12,rect.y+rect.height/2)
 await page.waitForTimeout(120)
 const sample=()=>cell.evaluate(el=>{const s=getComputedStyle(el,'::before');return {radius:s.borderRadius,transform:s.transform,width:parseFloat(s.width),height:parseFloat(s.height),origin:parseFloat(el.style.getPropertyValue('--bubble-x')),duration:s.transitionDuration}})
 const middle=await sample()
 assert.equal(middle.radius,'50%')
 assert.ok(middle.origin<30,'La burbuja nace donde entra el puntero')
 assert.ok(Math.abs(middle.width-middle.height)<2,'La forma debe ser circular')
 const scale=s=>Number(s.transform.match(/^matrix\(([^,]+)/)?.[1])
 assert.ok(scale(middle)>0&&scale(middle)<1,'El relleno crece progresivamente')
 await page.waitForTimeout(700)
 assert.ok(scale(await sample())>.99)
 await page.mouse.move(rect.x-5,rect.y+rect.height/2);await page.waitForTimeout(750)
 assert.ok(scale(await sample())<.01,'Se vacía al salir')
 await cell.focus();await page.waitForTimeout(750)
 assert.ok(scale(await sample())>.99,'También responde al teclado')
 await page.emulateMedia({reducedMotion:'reduce'})
 assert.ok(parseFloat((await sample()).duration)<.01,'Respeta movimiento reducido')
 console.log('PASS servicios: origen del puntero, círculo, llenado progresivo, salida, teclado y movimiento reducido')
} finally {await browser.close()}
