import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'})
 await page.goto(process.env.URL??'http://localhost:5173/',{waitUntil:'networkidle'})
 assert.deepEqual(await page.locator('#servicios .bento__title').allTextContents(), ['Diseño de interiores','Muebles personalizados','Delivery','Instalación y montaje'])
 assert.equal(await page.locator('#servicios .bento__cell').evaluateAll(nodes=>nodes.every(el=>el.tagName==='ARTICLE'&&el.tabIndex===-1&&!el.querySelector('a,button'))),true,'Las tarjetas deben ser informativas, sin enlaces ni acciones falsas')
 assert.equal(await page.locator('#servicios').getByText('Ver detalle',{exact:true}).count(),0)
 const cell=page.locator('.bento__cell').first()
 await cell.scrollIntoViewIfNeeded();await page.waitForTimeout(800)
 const rect=await cell.boundingBox()
 await page.mouse.move(0,0)
 await cell.hover({position:{x:12,y:rect.height/2}})
 await page.waitForTimeout(120)
 const sample=()=>cell.evaluate(el=>{const s=getComputedStyle(el,'::before');return {radius:s.borderRadius,transform:s.transform,width:parseFloat(s.width),height:parseFloat(s.height),origin:parseFloat(el.style.getPropertyValue('--bubble-x')),duration:s.transitionDuration}})
 const middle=await sample()
 assert.equal(middle.radius,'50%')
 assert.ok(middle.origin<30,'La burbuja nace donde entra el puntero')
 assert.ok(Math.abs(middle.width-middle.height)<2,'La forma debe ser circular')
 const scale=s=>Number(s.transform.match(/^matrix\(([^,]+)/)?.[1])
 assert.ok(scale(middle)>0&&scale(middle)<1,'El relleno crece progresivamente')
 await page.waitForTimeout(700)
 assert.ok(scale(await sample())>.99)
 await page.mouse.move(0,0);await page.waitForTimeout(750)
 assert.ok(scale(await sample())<.01,'Se vacía al salir')
 await cell.click()
 assert.ok(!page.url().endsWith('#servicios'),'Pulsar una tarjeta no debe navegar')
 const catalog=page.locator('.services__actions').getByRole('link',{name:'Explorar catálogo',exact:true})
 await catalog.focus()
 assert.ok(await catalog.evaluate(el=>el===document.activeElement),'Los accesos separados siguen disponibles por teclado')
 const quote=page.locator('.services__actions').getByRole('link',{name:'Cotizar mi proyecto',exact:true})
 assert.match(await quote.getAttribute('href'),/^https:\/\/wa\.me\//)
 await page.emulateMedia({reducedMotion:'reduce'})
 assert.ok(parseFloat((await sample()).duration)<.01,'Respeta movimiento reducido')
 await catalog.press('Enter')
 await page.getByRole('heading',{name:'Catálogo de muebles',exact:true}).waitFor()
 console.log('PASS servicios: cuatro tarjetas informativas, burbuja de entrada/salida, accesos separados y movimiento reducido')
} finally {await browser.close()}
