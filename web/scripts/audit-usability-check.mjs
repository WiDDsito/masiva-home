import assert from 'node:assert/strict'
import {chromium} from 'playwright-core'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
 for(const width of [390,1440]) {
  const page=await browser.newPage({viewport:{width,height:1000},reducedMotion:'reduce'})
  await page.goto(process.env.URL??'http://127.0.0.1:5174/',{waitUntil:'domcontentloaded'})
  await page.getByRole('link',{name:'Buscar productos',exact:true}).click({timeout:4000})
  await page.getByRole('heading',{name:'Catálogo de muebles',exact:true}).waitFor()
  assert.ok(await page.getByLabel('Buscar en el catálogo').evaluate(el=>el===document.activeElement))
  await page.getByLabel('Filtrar por categoría').selectOption('aparadores')
  await page.getByLabel('Buscar en el catálogo').fill('Arden')
  await page.getByLabel('Ordenar productos').selectOption('price-desc')
  await page.waitForFunction(()=>location.hash.includes('q=Arden')&&location.hash.includes('categoria=aparadores'))
  await page.reload({waitUntil:'domcontentloaded'})
  assert.equal(await page.getByLabel('Buscar en el catálogo').inputValue(),'Arden')
  assert.equal(await page.getByLabel('Filtrar por categoría').inputValue(),'aparadores')
  assert.equal(await page.getByLabel('Ordenar productos').inputValue(),'price-desc')
  assert.equal(await page.locator('.catalog-card').count(),1)
  if(width>900){
   await page.getByRole('button',{name:'Tienda',exact:true}).click()
   await page.locator('#mega-tienda .mega__link').filter({hasText:'Aparadores'}).click()
  }else{
   await page.getByRole('button',{name:'Abrir menú',exact:true}).click()
   await page.locator('.mobile-shop summary').click()
   await page.locator('#mega-tienda-movil .mega__link').filter({hasText:'Aparadores'}).click()
  }
  await page.waitForFunction(()=>document.querySelectorAll('.catalog-card').length===6)
  await page.goBack()
  await page.waitForFunction(()=>document.querySelector('#catalog-search')?.value==='Arden')
  assert.equal(await page.getByLabel('Ordenar productos').inputValue(),'price-desc')
  assert.equal(await page.locator('.catalog-card').count(),1)
  await page.getByRole('button',{name:'Limpiar filtros'}).click()
  await page.clock.install()
  await page.getByRole('button',{name:'Agregar Aparador Escanor al carrito',exact:true}).click()
  const notice=page.locator('.cart-notice')
  const open=notice.getByRole('button',{name:'Ver bolsa (1)',exact:true})
  await open.focus()
  await page.clock.fastForward(7000)
  assert.ok(await open.isVisible(),'El aviso debe permanecer mientras contiene el foco')
  assert.ok(await open.evaluate(el=>el===document.activeElement))
  await page.keyboard.press('Enter')
  await page.getByRole('dialog',{name:'Tu carrito',exact:true}).waitFor()
  await page.getByRole('button',{name:'Cerrar carrito',exact:true}).click()
  await page.waitForFunction(()=>document.activeElement?.textContent==='Ver bolsa (1)')
  assert.ok(await open.evaluate(el=>el===document.activeElement))
  await page.getByLabel('Buscar en el catálogo').focus()
  await page.mouse.move(0,0)
  await page.clock.fastForward(6100)
  await page.waitForFunction(()=>!document.querySelector('.cart-notice')?.classList.contains('is-visible'))
  await page.close()
  console.log(`PASS ${width}: búsqueda activa, filtros recuperables y aviso operable por teclado`)
 }
}finally{await browser.close()}
