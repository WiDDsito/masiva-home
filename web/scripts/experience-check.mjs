import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright-core'
const browser = await chromium.launch({channel:'chrome',headless:true})
const url = process.env.URL ?? 'http://localhost:5173/'
const errors=[]
const output=process.env.SHOTS_DIR ?? '.screenshots'
await mkdir(output,{recursive:true})
try {
 for (const width of [320,390,768,1024,1440]) {
  const context=await browser.newContext({viewport:{width,height:1000},reducedMotion:'reduce'})
  const page=await context.newPage()
  page.on('response',r=>{if(r.status()>=400) console.log('HTTP',r.status(),r.url())})
  page.on('pageerror',e=>errors.push(e.message))
  page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text())})
  await page.goto(url,{waitUntil:'networkidle'})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Sin desborde a ${width}`)
  assert.equal(await page.locator('.product').count(),2)
  await page.getByRole('link',{name:'Buscar productos',exact:true}).click()
  await page.locator('#catalog-search').fill('escanor')
  assert.equal(await page.locator('.catalog-card').count(),1)
  await page.getByRole('button',{name:'Agregar Aparador Escanor al carrito'}).click()
  await page.getByRole('button',{name:'Carrito, 1 productos'}).click()
  await page.getByRole('button',{name:'Aumentar cantidad de Aparador Escanor'}).click()
  await page.waitForFunction(()=>document.querySelector('.cart-count')?.textContent==='2')
  assert.ok((await page.locator('.cart-summary').innerText()).includes('1,918'))
  const message=await page.getByRole('link',{name:'Consultar mi selección por WhatsApp'}).getAttribute('href')
  assert.ok(decodeURIComponent(message).includes('200100001001'))
  if(width===1440) await page.screenshot({path:`${output}/carrito-desktop.png`})
  await page.keyboard.press('Escape')
  await page.waitForFunction(()=>!document.querySelector('#shopping-bag').open)
  assert.equal(await page.locator('dialog').isVisible(),false)
  assert.ok((await page.locator(':focus').getAttribute('aria-label')).includes('Carrito'))
  await page.reload({waitUntil:'networkidle'})
  await page.getByRole('button',{name:'Carrito, 2 productos'}).click()
  await page.getByRole('button',{name:'Eliminar Aparador Escanor',exact:true}).click()
  await page.getByText('Tu próximo mueble te espera.').waitFor()
  assert.ok(await page.getByText('Tu próximo mueble te espera.').isVisible())
  await page.keyboard.press('Escape')
  await page.waitForFunction(()=>!document.querySelector('#shopping-bag').open)
  await page.locator('#catalog-search').fill('no-existe')
  await page.getByRole('heading',{name:'No encontramos ese mueble.'}).waitFor()
  assert.ok(await page.getByRole('heading',{name:'No encontramos ese mueble.'}).isVisible())
  await page.getByRole('button',{name:'Limpiar filtros'}).click()
  await page.getByRole('combobox',{name:'Filtrar por categoría'}).selectOption('sala')
  assert.equal(await page.locator('.catalog-card').count(),3)
  await page.getByRole('combobox',{name:'Ordenar productos'}).selectOption('price-asc')
  assert.ok((await page.locator('.catalog-card').first().innerText()).includes('Fabela'))
  await page.getByRole('combobox',{name:'Filtrar por categoría'}).selectOption('all')
  await page.getByRole('banner').getByRole('link',{name:'Masiva Home, ir al inicio',exact:true}).click()
  await page.locator('#showroom').scrollIntoViewIfNeeded()
  await page.locator('.showroom__stage canvas').waitFor()
  await page.waitForTimeout(1800)
  assert.ok(await page.locator('.showroom__stage canvas').isVisible())
  await page.getByRole('button',{name:'Centro de mesa',exact:true}).click()
  await page.waitForTimeout(500)
  assert.equal(await page.getByRole('button',{name:'Centro de mesa',exact:true}).getAttribute('aria-pressed'),'true')
  if(width===1440 || width===390) {
   await page.locator('#showroom').evaluate(el=>el.scrollIntoView({block:'start'}))
   await page.locator('#showroom').screenshot({path:`${output}/showroom-${width}.png`})
   await page.evaluate(()=>scrollTo(0,0))
   await page.screenshot({path:`${output}/inicio-${width}.png`,fullPage:true})
  }
  console.log(`PASS ${width}px: layout, búsqueda, filtros, carrito, persistencia, teclado y showroom`)
  await context.close()
 }
 assert.deepEqual(errors,[])
 const context=await browser.newContext({viewport:{width:1440,height:1000}})
 const page=await context.newPage()
 await page.goto(url,{waitUntil:'networkidle'})
 await page.locator('#showroom').scrollIntoViewIfNeeded()
 await page.waitForTimeout(1500)
 await page.emulateMedia({reducedMotion:'reduce'})
 assert.equal(await page.locator('.showroom__stage').evaluate(el=>getComputedStyle(el).opacity),'1')
 await context.close()
 console.log('PASS cambio de preferencia de movimiento en ejecución; consola sin errores')
} finally {await browser.close()}
