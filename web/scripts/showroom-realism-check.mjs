import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
 for(const width of [390,1440]) {
  const page=await browser.newPage({viewport:{width,height:1000},reducedMotion:'no-preference'})
  const errors=[];page.on('pageerror',error=>errors.push(error.message));page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
  await page.goto(process.env.URL??'http://localhost:5173/',{waitUntil:'networkidle'})
  const video=page.locator('.hero__video')
  await video.waitFor()
  await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2)
  assert.ok(await video.evaluate(el=>el.muted&&el.defaultMuted&&el.volume===0&&el.playsInline&&!el.controls))
  await page.waitForFunction(()=>document.querySelector('video')?.currentTime>0)
  await video.evaluate(el=>{el.muted=false;el.volume=1})
  await page.waitForFunction(()=>{const el=document.querySelector('video');return el.muted&&el.volume===0})
  await page.getByRole('button',{name:'Pausar video de portada'}).click()
  assert.equal(await video.evaluate(el=>el.paused),true)
  await page.getByRole('button',{name:'Reproducir video de portada'}).click()
  await page.locator('#showroom').scrollIntoViewIfNeeded();await page.locator('canvas').waitFor()
  await page.waitForFunction(()=>document.querySelector('canvas')?.dataset.cameraMoving==='false')
  assert.deepEqual(await page.getByRole('tablist',{name:'Ambientes del showroom'}).getByRole('tab').allTextContents(),['Sala','Comedor','Dormitorio'])
  assert.equal(await page.getByRole('tab',{name:'Sala',exact:true}).getAttribute('aria-selected'),'true')
  assert.deepEqual(await page.getByRole('group',{name:'Productos de Sala'}).getByRole('button').allTextContents(),['Centro de mesa','Mesa de TV'])
  assert.equal(await video.evaluate(el=>el.paused),true)
  const distance=await page.locator('canvas').getAttribute('data-camera-distance')
  await page.getByRole('button',{name:'Centro de mesa',exact:true}).click()
  await page.waitForFunction(()=>{const c=document.querySelector('canvas');return c?.dataset.cameraMoving==='false'&&c?.dataset.cameraFocus==='Centro de mesa'})
  assert.ok(Number(await page.locator('canvas').getAttribute('data-camera-distance'))<Number(distance)*.9)
  assert.ok(await page.locator('#showroom').getByRole('heading',{name:'Mesa de centro Fabela',exact:true}).isVisible())
  assert.ok(await page.getByRole('img',{name:'Fotografía de referencia de Mesa de centro Fabela'}).isVisible())
  await page.getByRole('button',{name:'Centro de mesa',exact:true}).click()
  await page.waitForFunction(()=>{const c=document.querySelector('canvas');return c?.dataset.cameraMoving==='false'&&c?.dataset.cameraFocus==='none'})
  assert.ok(Math.abs(Number(await page.locator('canvas').getAttribute('data-camera-distance'))-Number(distance))<.02)
  await page.getByRole('tab',{name:'Comedor',exact:true}).click()
  assert.deepEqual(await page.getByRole('group',{name:'Productos de Comedor'}).getByRole('button').allTextContents(),['Aparador Escanor'])
  await page.getByRole('button',{name:'Aparador Escanor',exact:true}).click()
  await page.locator('#showroom').getByRole('heading',{name:'Aparador Escanor',exact:true}).waitFor()
  await page.getByRole('button',{name:'Vista general',exact:true}).click()
  await page.getByRole('tab',{name:'Dormitorio',exact:true}).click()
  assert.deepEqual(await page.getByRole('group',{name:'Productos de Dormitorio'}).getByRole('button').allTextContents(),['Ropero'])
  await page.getByRole('button',{name:'Ropero',exact:true}).click()
  await page.waitForFunction(()=>{const c=document.querySelector('canvas');return c?.dataset.cameraMoving==='false'&&c?.dataset.cameraFocus==='Ropero'})
  await page.locator('canvas').click({position:{x:width*.95,y:40}})
  await page.waitForFunction(()=>{const c=document.querySelector('canvas');return c?.dataset.cameraMoving==='false'&&c?.dataset.cameraFocus==='none'})
  await page.locator('#showroom').screenshot({path:`.screenshots/realism-${width}.png`})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  assert.deepEqual(errors,[])
  console.log(`PASS ${width}px: video sin sonido, reproducción, grupos de productos, zoom de selección, deselección y encuadre`)
  await page.close()
 }
} finally {await browser.close()}
