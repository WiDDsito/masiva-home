import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
 for (const width of [390,1440]) {
  const page=await browser.newPage({viewport:{width,height:1000},reducedMotion:width===390?'reduce':'no-preference'})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(process.env.URL??'http://127.0.0.1:5174/',{waitUntil:'networkidle'})
  const image=page.getByRole('button',{name:'Ver detalles de Aparador Escanor',exact:true})
  await image.click({timeout:4000})
  const detail=page.getByRole('dialog',{name:'Aparador Escanor',exact:true})
  await detail.waitFor()
  assert.ok((await detail.innerText()).includes('130 × 100 × 35'))
  assert.ok(await page.getByRole('button',{name:'Cerrar detalles del producto'}).isVisible())
  await page.keyboard.press('Escape')
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Ver detalles de Aparador Escanor')
  assert.equal(await image.evaluate(el=>el===document.activeElement),true)
  await page.getByRole('button',{name:'Agregar Aparador Escanor al carrito',exact:true}).click()
  assert.equal(await detail.count(),0)
  await page.getByRole('button',{name:'Carrito, 1 productos'}).click()
  await page.keyboard.press('Escape')
  await image.focus();await page.keyboard.press('Enter')
  await page.getByRole('dialog',{name:'Aparador Escanor',exact:true}).waitFor()
  await page.getByRole('dialog',{name:'Aparador Escanor',exact:true}).getByRole('button',{name:'Agregar Aparador Escanor al carrito',exact:true}).click()
  await page.getByRole('button',{name:'Carrito, 2 productos'}).waitFor()
  await page.getByRole('link',{name:'Ver catálogo completo',exact:true}).click()
  await page.getByRole('heading',{name:'Catálogo completo',exact:true}).waitFor()
  await page.getByRole('button',{name:'Ver detalles de Ropero Runa',exact:true}).click()
  await page.getByRole('dialog',{name:'Ropero Runa',exact:true}).waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('.btn:not(.magnetic .btn)').count(),0,'Todos los botones de acción comparten el efecto')
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await page.waitForFunction(() => !document.documentElement.hasAttribute('data-view-transition'))
  if (width === 1440) {
   const button=page.getByRole('button',{name:'Agregar Aparador Escanor al carrito',exact:true})
   await button.scrollIntoViewIfNeeded()
   const wrapper=button.locator('xpath=../..')
   const box=await wrapper.boundingBox()
   await page.mouse.move(box.x+box.width*.8,box.y+box.height*.5)
   await page.waitForTimeout(250)
   const surface=wrapper.locator('.magnetic__surface')
   const displacement=await surface.evaluate(el=>new DOMMatrix(getComputedStyle(el).transform).m41)
   assert.ok(displacement>1,'El botón responde al puntero con el muelle compartido')
   await page.mouse.move(box.x-30,box.y-30)
   await page.waitForTimeout(1000)
   assert.ok(Math.abs(await surface.evaluate(el=>new DOMMatrix(getComputedStyle(el).transform).m41))<.2,'El rebote vuelve a reposo')
  }
  assert.deepEqual(errors,[])
  console.log(`PASS ${width}px: imagen y carrito independientes, ficha, teclado, foco y efecto compartido`)
  await page.close()
 }
} finally {await browser.close()}
